# Plural/inflected forms that appear in queries vs. the KB. Explicit, so nothing surprising happens.
LEMMAS: dict[str, str] = {
    "fees": "fee",
    "prices": "price",
    "courses": "course",
    "classes": "class",
    "batches": "batch",
    "mentors": "mentor",
    "certificates": "certificate",
    "lessons": "lesson",
    "modules": "module",
    "videos": "video",
    "projects": "project",
    "stores": "store",
    "seats": "seat",
    "trainers": "trainer",
    "teachers": "teacher",
    "installments": "installment",
}

_TOKEN_RE = re.compile(r"[a-z0-9]+(?:[.'][a-z0-9]+)*")
_THOUSANDS_RE = re.compile(r"(?<=\d),(?=\d{2,3}\b)")


def normalize(text: str) -> str:
    """NFKC, lower-case, unify quotes, drop thousands separators ('30,000' -> '30000'), collapse spaces."""
    text = unicodedata.normalize("NFKC", text).lower()
    text = text.replace("’", "'").replace("‘", "'")
    previous = None
    while previous != text:  # '1,25,000' needs two passes
        previous = text
        text = _THOUSANDS_RE.sub("", text)
    return re.sub(r"\s+", " ", text).strip()


def tokenize(text: str) -> list[str]:
    tokens = []
    for raw in _TOKEN_RE.findall(normalize(text)):
        token = raw[:-2] if raw.endswith("'s") else raw
        tokens.append(LEMMAS.get(token, token))
    return tokens


def analyze(text: str) -> list[str]:
    """Tokens used for BM25 on both sides: normalised, lemmatised, stopwords removed."""
    return [t for t in tokenize(text) if t not in STOPWORDS]
